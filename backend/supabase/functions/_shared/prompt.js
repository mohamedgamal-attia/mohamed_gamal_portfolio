/* The markers must not be forgeable from inside the customer's own text, or a
 * description could close the fence early and continue as if it were trusted.
 * Any occurrence in the input is neutralised before fencing. */
const FENCE_BEGIN = '<<<CUSTOMER_DESCRIPTION_BEGIN>>>';
const FENCE_END   = '<<<CUSTOMER_DESCRIPTION_END>>>';

/** Remove anything that could impersonate the fence or a chat role marker. */
export function neutraliseFence(text) {
  return String(text ?? '')
    .replace(/<<<\s*CUSTOMER_DESCRIPTION_(BEGIN|END)\s*>>>/gi, '[removed]')
    .replace(/<<</g, '<‌<‌<')   // zero-width non-joiner breaks the literal
    .replace(/>>>/g, '>‌>‌>')
    .replace(/^\s*(system|assistant|model|user)\s*:/gim, '$1 -');
}

/**
 * Build the user message. Structured fields are rendered as labelled values;
 * only the free-text description is fenced, because it is the only field the
 * customer can write prose into.
 */
export function buildUserMessage({ language, countryName, projectType, description,
                                   desiredTimeline, clientBudget, complexity,
                                   hardFloorUsd, allowedMinUsd, allowedMaxUsd }) {
  const none = language === 'ar' ? 'غير محدد' : 'not specified';
  return [
    `Preferred language: ${language}`,
    `Country: ${neutraliseFence(countryName)}`,
    `Project type: ${projectType}`,
    'Description:',
    FENCE_BEGIN,
    neutraliseFence(description),
    FENCE_END,
    '',
    `Desired timeline: ${neutraliseFence(desiredTimeline) || none}`,
    `Client-stated budget: ${neutraliseFence(clientBudget) || none}`,
    '',
    `Complexity: ${complexity}`,
    `Hard floor USD: ${hardFloorUsd}`,
    `Allowed estimate range USD: ${allowedMinUsd} - ${allowedMaxUsd}`,
    '',
    'Return only the required JSON.',
  ].join('\n');
}

/** The response schema handed to the Gemini structured-output API. */
export const RESPONSE_SCHEMA = {
  type: 'object',
  properties: {
    language:          { type: 'string', enum: ['ar', 'en'] },
    project_type:      { type: 'string' },
    summary:           { type: 'string' },
    recommended_scope: { type: 'array', items: { type: 'string' } },
    price_min_usd:     { type: 'integer' },
    price_max_usd:     { type: 'integer' },
    estimated_timeline:{ type: 'string' },
    assumptions:       { type: 'array', items: { type: 'string' } },
    customer_message:  { type: 'string' },
    meeting_cta:       { type: 'string' },
    injection_attempt: { type: 'boolean' },
  },
  required: [
    'language', 'project_type', 'summary', 'recommended_scope',
    'price_min_usd', 'price_max_usd', 'estimated_timeline',
    'assumptions', 'customer_message', 'meeting_cta',
  ],
};

